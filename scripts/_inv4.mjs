import { chromium } from "playwright";
import { writeFileSync } from "node:fs";
const base = "http://127.0.0.1:3765";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1920, height: 1080 } });
const snap = async (name, loc = p.locator("body")) => writeFileSync(`/tmp/inv/${name}.aria.txt`, await loc.ariaSnapshot());
await p.goto(base + "/harta?household=RO-TM-001", { waitUntil: "networkidle" });
await p.waitForTimeout(1500);
await p.getByRole("button", { name: "Analiză detaliată" }).last().click();
await p.waitForTimeout(1000);
const panel = p.getByRole("complementary").last();
await snap("harta_tm_panel", panel);
const sim = p.getByRole("button", { name: "Simulează soluția" });
if (await sim.count()) { await sim.click(); await p.waitForTimeout(1200); await snap("harta_tm_whatif", panel); await p.screenshot({ path: "/tmp/inv/whatif.jpg", quality: 70 }); }
await p.goto(base + "/harta?household=RO-IF-002", { waitUntil: "networkidle" });
await p.waitForTimeout(1500);
await p.getByRole("button", { name: "Analiză detaliată" }).last().click();
await p.waitForTimeout(800);
await p.getByRole("button", { name: /Alocă intervenție O&M/ }).click();
await p.waitForTimeout(800);
await snap("alert_dialog", p.getByRole("alertdialog").or(p.getByRole("dialog")).first());
await p.screenshot({ path: "/tmp/inv/alert.jpg", quality: 70 });
await p.goto(base + "/triaj?household=RO-BV-004", { waitUntil: "networkidle" });
await p.waitForTimeout(1500);
await snap("triaj_bv", p.locator("main"));
await p.screenshot({ path: "/tmp/inv/triaj_bv.jpg", quality: 70 });
await p.goto(base + "/prosumator?household=RO-CJ-003", { waitUntil: "networkidle" });
await p.waitForTimeout(1500);
await snap("pros_cj", p.locator("main"));
await p.goto(base + "/", { waitUntil: "networkidle" });
await p.waitForTimeout(1500);
await snap("landing", p.locator("body"));
await b.close();
