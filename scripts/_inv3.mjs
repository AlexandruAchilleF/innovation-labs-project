import { chromium } from "playwright";
const base = "http://127.0.0.1:3765";
const b = await chromium.launch();
const ph = await b.newPage({ viewport: { width: 400, height: 860 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
await ph.goto(base + "/prosumator?household=RO-IF-002", { waitUntil: "networkidle" });
await ph.waitForTimeout(1500);
await ph.locator("main").screenshot({ path: "/tmp/inv/phone_full.jpg", quality: 60, scale: "css" });
const h = await ph.evaluate(() => [document.scrollingElement.scrollHeight, document.querySelector("main").scrollHeight, getComputedStyle(document.body).overflow]);
console.log(h);
await b.close();
